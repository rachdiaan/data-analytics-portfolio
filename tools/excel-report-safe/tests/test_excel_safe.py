"""Tests for excel_safe.

The serial-date arithmetic and the overwrite guard are tested with a fake COM cell,
so they run anywhere. `health` is tested against a workbook generated by openpyxl.
Anything that needs Excel itself is skipped when Excel is not installed, and says so
rather than passing quietly.

    python tools/excel-report-safe/tests/test_excel_safe.py
"""
import datetime as dt
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from excel_safe import (  # noqa: E402
    EXCEL_EPOCH, from_serial, health, to_serial, write_values,
)


# --------------------------------------------------------------- serial arithmetic
def test_known_serials():
    """Anchors every spreadsheet user can check by hand in Excel."""
    assert to_serial(dt.date(1899, 12, 31)) == 1.0
    assert to_serial(dt.date(1900, 1, 1)) == 2.0        # 1900 leap-year bug territory
    assert to_serial(dt.date(2026, 10, 13)) == 46308.0
    assert from_serial(46308.0).date() == dt.date(2026, 10, 13)


def test_round_trip_is_exact_for_dates():
    d = EXCEL_EPOCH
    for k in range(0, 60000, 997):
        day = d + dt.timedelta(days=k)
        assert from_serial(to_serial(day)).date() == day, day


def test_datetime_keeps_its_time():
    got = from_serial(to_serial(dt.datetime(2026, 10, 13, 17, 0, 0)))
    assert got == dt.datetime(2026, 10, 13, 17, 0, 0), got


def test_the_bug_this_exists_for():
    """A -7h shift lands on the previous day at 17:00, and nothing raises.

    This is the arithmetic of the failure, not a test of pywin32: it shows why a
    date must be sent as a serial and read back as one.
    """
    intended = dt.date(2026, 10, 13)
    shifted = dt.datetime.combine(intended, dt.time()) - dt.timedelta(hours=7)
    assert shifted.date() == dt.date(2026, 10, 12)
    assert shifted.time() == dt.time(17, 0)
    # as serials the difference is a fraction of a day, which is what the verify
    # step in write_values() detects
    assert abs(to_serial(shifted) - to_serial(intended) + 7 / 24) < 1e-9


# ---------------------------------------------------------------- overwrite guard
class FakeCell:
    def __init__(self, value=None):
        self.Value2 = value
        self.Value = value


class FakeSheet:
    """Enough of a COM worksheet to exercise write_values, including the read-back."""

    def __init__(self, cells=None):
        self.cells = {k: FakeCell(v) for k, v in (cells or {}).items()}

    def Range(self, ref):
        return self.cells.setdefault(ref, FakeCell())


def test_refuses_to_overwrite_a_filled_cell():
    ws = FakeSheet({"B5": "do not clobber"})
    try:
        write_values(ws, {"B5": "new"})
    except ValueError as e:
        assert "not empty" in str(e), e
    else:
        raise AssertionError("a filled cell was overwritten without permission")


def test_overwrites_when_told_to():
    ws = FakeSheet({"B5": "old"})
    assert write_values(ws, {"B5": "new"}, allow_overwrite=True) == 1
    assert ws.Range("B5").Value == "new"


def test_blank_and_whitespace_count_as_empty():
    ws = FakeSheet({"A1": None, "A2": "   "})
    assert write_values(ws, {"A1": 1, "A2": 2}) == 2


def test_dates_are_written_as_serials():
    ws = FakeSheet()
    write_values(ws, {"F5": dt.date(2026, 10, 13)})
    assert ws.Range("F5").Value2 == 46308.0


def test_verify_catches_a_shifted_write():
    """A sheet that applies a -7h offset must make write_values fail, loudly."""

    class ShiftingSheet(FakeSheet):
        def Range(self, ref):
            cell = super().Range(ref)
            real = type(cell)

            class Shifter(real):          # writes land 7 hours earlier
                def __setattr__(self, k, v):
                    if k == "Value2" and isinstance(v, float):
                        v = v - 7 / 24
                    object.__setattr__(self, k, v)

            cell.__class__ = Shifter
            return cell

    try:
        write_values(ShiftingSheet(), {"F5": dt.date(2026, 10, 13)})
    except RuntimeError as e:
        assert "UTC offset" in str(e), e
    else:
        raise AssertionError("a shifted write was accepted")


# ------------------------------------------------------------------------- health
def test_health_counts_formatting_and_validation():
    try:
        from openpyxl import Workbook
        from openpyxl.formatting.rule import CellIsRule
        from openpyxl.worksheet.datavalidation import DataValidation
    except ImportError:
        print("  (skipped: openpyxl not installed)")
        return

    wb = Workbook()
    ws = wb.active
    ws.title = "Tracker"
    ws["A1"] = "status"
    ws.conditional_formatting.add(
        "A2:A50", CellIsRule(operator="equal", formula=['"Done"']))
    ws.conditional_formatting.add(
        "B2:B50", CellIsRule(operator="equal", formula=['"At Risk"']))
    dv = DataValidation(type="list", formula1='"Planned,Doing,Done"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add("C2:C50")

    path = os.path.join(tempfile.mkdtemp(prefix="excel_safe_"), "t.xlsx")
    wb.save(path)
    wb.close()

    rows = health(path)
    assert len(rows) == 1, rows
    assert rows[0].conditional_formats == 2, rows[0]
    assert rows[0].validations == 1, rows[0]
    os.remove(path)


